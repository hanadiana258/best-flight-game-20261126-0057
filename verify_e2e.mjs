import { chromium } from '/root/.npm/_npx/360550e4913b8759/node_modules/playwright/index.mjs';
const b = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
p.on('console', m => m.type() === 'error' && errs.push(m.text()));
p.on('pageerror', x => errs.push(x.message));
await p.goto('http://127.0.0.1:8096/', { waitUntil: 'networkidle' });
await p.waitForTimeout(1200);
await p.screenshot({ path: 'verify/1-title.jpg', quality: 85 });
await p.keyboard.press('Enter');
await p.waitForTimeout(2500);
await p.keyboard.down('a'); await p.waitForTimeout(400); await p.keyboard.up('a');
await p.screenshot({ path: 'verify/2-chase-bank.jpg', quality: 85 });
await p.keyboard.press('v');
await p.waitForTimeout(800);
await p.screenshot({ path: 'verify/3-cockpit.jpg', quality: 85 });
await p.keyboard.press('v');
await p.waitForTimeout(4000);
await p.keyboard.down('w'); await p.waitForTimeout(1500); await p.keyboard.up('w');
await p.screenshot({ path: 'verify/4-approach.jpg', quality: 85 });
const fps = await p.evaluate(() => window.__fps ?? null).catch(() => null);
console.log(JSON.stringify({ errors: errs, title: await p.title(), canvas: await p.locator('canvas').count(), fps }));
await b.close();
